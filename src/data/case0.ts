import type { CaseDef, HiddenObject, Hotspot } from '../types';

/**
 * Case 0, the tutorial. Later cases are another CaseDef: rooms, hidden objects,
 * clues, an economy, and an ordered steps array. Scene art is chosen by
 * RoomDef.painter (`office`, `shop`, `nook`, `stock`) and loaded in BootScene.
 * Hotspot coordinates are normalised to the 1280×720 painting.
 */
const ellipse = (cx: number, cy: number, rx: number, ry: number): Hotspot => ({
  kind: 'ellipse',
  cx,
  cy,
  rx,
  ry,
});

const at = (id: string, roomId: string, name: string, cx: number, cy: number, rx: number, ry: number, extra?: Partial<HiddenObject>): HiddenObject => ({
  id,
  roomId,
  name,
  spot: ellipse(cx, cy, rx, ry),
  ...extra,
});

